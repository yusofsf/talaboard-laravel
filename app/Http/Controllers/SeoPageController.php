    private function schema(array $meta, string $canonical): array
    {
        $schema = [
            '@context' => 'https://schema.org',
            '@type' => 'WebPage',
            'name' => $meta['title'],
            'description' => $meta['description'],
            'url' => $canonical,
            'inLanguage' => 'fa-IR',
            'isPartOf' => [
                '@type' => 'WebSite',
                'name' => config('seo.site_name'),
                'url' => rtrim(config('seo.url'), '/') . '/',
            ],
            'about' => array_map(
                fn (string $name) => ['@type' => 'Thing', 'name' => $name],
                $meta['keywords'] ?? []
            ),
        ];

        if (! empty($meta['faq'])) {
            $schema = [
                '@context' => 'https://schema.org',
                '@graph' => [
                    $schema,
                    [
                        '@type' => 'FAQPage',
                        'mainEntity' => array_map(fn (array $item) => [
                            '@type' => 'Question',
                            'name' => $item['question'],
                            'acceptedAnswer' => [
                                '@type' => 'Answer',
                                'text' => $item['answer'],
                            ],
                        ], $meta['faq']),
                    ],
                ],
            ];
        }

        return $schema;
    }
