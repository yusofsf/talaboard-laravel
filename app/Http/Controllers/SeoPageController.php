    public function show(string $page): Response
    {
        $pages = [
            ...config('seo.public_pages', []),
            ...config('seo.keyword_pages', []),
        ];
        abort_unless(isset($pages[$page]), 404);

        $meta = $pages[$page];
        $siteUrl = rtrim(config('seo.url'), '/');
        $canonical = $siteUrl . $meta['path'];
        $prices = Schema::hasTable('price_snapshots')
            ? (PriceSnapshot::latestPayload() ?? [])
            : [];

        return response()->view('seo.landing', [
            'pageKey' => $page,
            'meta' => [
                ...$meta,
                'canonical' => $canonical,
                // Keep narrow keyword variants available to visitors without
                // asking search engines to index near-duplicate landing pages.
                'robots' => array_key_exists($page, config('seo.keyword_pages', []))
                    ? 'noindex, follow'
                    : 'index, follow, max-image-preview:large',
            ],
            'prices' => $prices,
            'schema' => $this->schema($meta, $canonical),
            'guide' => $this->guide($page),
        ]);
    }

