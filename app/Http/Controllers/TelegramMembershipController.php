    private function vipUserForChat(Request $request): User
    {
        $chatId = $request->validate(['telegram_chat_id' => ['required', 'string', 'max:32']])['telegram_chat_id'];
        $user = User::query()->where('telegram_chat_id', $chatId)->first();
        abort_unless($user && $user->isVipMember(), 403, 'عضویت ویژه فعال نیست.');

        return $user;
    }

    private function roomAsset(TradeRoomOffer $offer): string
    {
        if ($offer->metal === 'gold') return 'gold';
        if ($offer->metal === 'silver') return 'silver_'.$offer->purity;

        return ['bahar' => 'full_coin', 'nim' => 'half_coin', 'rob' => 'quarter_coin'][$offer->item] ?? 'coin';
    }

    private function membershipPayload(User $user): array
    {
        return [
            'linked' => true,
            'vip' => $user->isVipMember(),
            'user_id' => $user->id,
            'name' => $user->name,
            'phone' => $user->phone,
            'membership_level' => $user->membership_level,
            'membership_status' => $user->membership_status,
            'trade_room_commission_percent' => (float) Setting::get('trade_room_commission_percent', 0.1),
            'asset_collateral_available' => $this->availableCollateralAmount($user),
        ];
    }

    private function availableCollateralAmount(User $user): int
    {
        return (int) AssetCollateralRequest::query()
            ->where('user_id', $user->id)
            ->where('status', 'approved')
            ->get()
            ->sum(fn (AssetCollateralRequest $collateral) => $collateral->availableAmount());
    }

    private function reserveCollateral(User $user, int $amount): void
    {
        if ($amount <= 0) {
            return;
        }

        $remaining = $amount;
        AssetCollateralRequest::query()
            ->where('user_id', $user->id)
            ->where('status', 'approved')
            ->whereColumn('used_amount', '<', 'trade_limit_amount')
            ->lockForUpdate()
            ->orderBy('id')
            ->get()
            ->each(function (AssetCollateralRequest $collateral) use (&$remaining) {
                if ($remaining <= 0) {
                    return;
                }

                $use = min($remaining, $collateral->availableAmount());
                $collateral->increment('used_amount', $use);
                $remaining -= $use;
            });

        abort_if($remaining > 0, 422, 'اعتبار بیعانه دارایی کافی نیست.');
    }
