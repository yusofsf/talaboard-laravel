    }

    /**
     * Consumes a short-lived code generated by the signed-in website user.
     * This endpoint is called only by the Telegram bot, using its shared secret.
     */
    public function connect(Request $request): JsonResponse
    {
        $this->authorize($request);
        $data = $request->validate([
            'code' => ['required', 'string', 'digits:6'],
            'telegram_user_id' => ['required', 'integer', 'min:1'],
            'telegram_chat_id' => ['required', 'integer'],
            'telegram_username' => ['nullable', 'string', 'max:255'],
        ]);

        $user = DB::transaction(function () use ($data) {
            $code = TelegramLinkCode::query()
                ->where('code_hash', hash('sha256', $data['code']))
                ->whereNull('used_at')
                ->where('expires_at', '>', now())
                ->lockForUpdate()
                ->first();

            abort_unless($code, 422, 'کد اتصال نامعتبر یا منقضی شده است.');
            $user = User::query()->lockForUpdate()->findOrFail($code->user_id);

            $conflict = TelegramConnection::query()
                ->where(function ($query) use ($data) {
                    $query->where('telegram_user_id', (string) $data['telegram_user_id'])
                        ->orWhere('telegram_chat_id', (string) $data['telegram_chat_id']);
                })
                ->where('user_id', '!=', $user->id)
                ->exists();
            abort_if($conflict, 422, 'این حساب تلگرام به کاربر دیگری متصل است.');

            TelegramConnection::updateOrCreate(
                ['user_id' => $user->id],
                [
                    'telegram_user_id' => (string) $data['telegram_user_id'],
                    'telegram_chat_id' => (string) $data['telegram_chat_id'],
                    'telegram_username' => $data['telegram_username'] ?? null,
                    'connected_at' => now(),
                ],
            );

            // Existing bot endpoints still identify a member by chat ID.
            $user->update(['telegram_chat_id' => (string) $data['telegram_chat_id']]);
            $code->update(['used_at' => now()]);

            return $user;
        });

        return response()->json($this->membershipPayload($user));
    }

    public function member(Request $request): JsonResponse
    {
        $this->authorize($request);
        $data = $request->validate(['telegram_chat_id' => ['required', 'string', 'max:32']]);
        $user = User::query()->where('telegram_chat_id', $data['telegram_chat_id'])->first();

        if (! $user) {
            return response()->json(['linked' => false, 'vip' => false, 'membership_level' => 0, 'membership_status' => 'none']);
        }

        return response()->json($this->membershipPayload($user));
    }

