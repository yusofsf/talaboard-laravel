    public function trade(Request $request, PriceService $prices): JsonResponse
    {
        $this->authorize($request);
        $user = $this->vipUserForChat($request);
        $data = $request->validate([
            'side' => ['required', 'in:buy,sell'],
            'unit' => ['required', 'in:mesghal,gram'],
            'quantity' => ['required', 'numeric', 'min:0.001'],
        ]);

        $item = $data['unit'] === 'mesghal' ? 'mithqal' : 'geram';
        $label = $data['unit'] === 'mesghal' ? 'مثقال طلا' : 'گرم طلا';
        $quantity = (float) $data['quantity'];
        $grams = $data['unit'] === 'mesghal' ? round($quantity * (float) env('MITHQAL_GRAMS', 4.3318), 4) : $quantity;
        abort_if($grams < 10, 422, 'حداقل مقدار معامله ۱۰ گرم است.');
        $price = (float) data_get($prices->all(), "gold.{$item}");
        abort_unless($price > 0, 422, 'قیمت در دسترس نیست.');
        $total = (int) round($quantity * $price);

        $transaction = DB::transaction(function () use ($user, $data, $item, $label, $quantity, $grams, $price, $total) {
            $user = User::query()->lockForUpdate()->findOrFail($user->id);
            if ($data['side'] === 'buy') {
                abort_if($user->walletBalance() < $total, 422, 'موجودی کیف پول کافی نیست.');
                WalletTransaction::create(['user_id' => $user->id, 'amount' => -$total, 'type' => 'withdraw', 'description' => "خرید {$label} از ربات"]);
                GoldLedger::create(['user_id' => $user->id, 'grams' => $grams, 'type' => 'purchase', 'description' => "خرید {$label} از ربات"]);
            } else {
                abort_if($user->goldBalance() < $grams, 422, 'موجودی طلای شما کافی نیست.');
                WalletTransaction::create(['user_id' => $user->id, 'amount' => $total, 'type' => 'deposit', 'description' => "فروش {$label} از ربات"]);
                GoldLedger::create(['user_id' => $user->id, 'grams' => -$grams, 'type' => 'sale', 'description' => "فروش {$label} از ربات"]);
            }

            return Transaction::create([
                'user_id' => $user->id,
                'type' => $data['side'],
                'item' => $item,
                'item_label' => $label,
                'quantity' => $quantity,
                'price_per_unit' => (int) $price,
                'total' => $total,
                'status' => 'active',
                'admin_note' => 'ثبت‌شده از ربات تلگرام',
            ]);
        });
        ActivityLog::record('telegram_trade', 'trade', "ثبت {$data['side']} {$label} از ربات", $user->id);

        return response()->json($transaction, 201);
    }

    /** فهرست سفارش‌های باز اتاق معاملاتی، بدون اطلاعات هویتی طرفین. */
    public function tradeRoomOffers(Request $request, TradeRoomExpiryService $expiry): JsonResponse
    {
        $this->authorize($request);
        $user = $this->vipUserForChat($request);
        $expiry->expireOpenOffers();

        $data = $request->validate([
            'mine' => ['nullable'],
            'status' => ['nullable'],
        ]);
        $mine = filter_var($data['mine'] ?? false, FILTER_VALIDATE_BOOL);
        $statuses = collect((array) ($data['status'] ?? []))
            ->flatMap(fn ($status) => is_string($status) ? explode(',', $status) : [$status])
            ->map(fn ($status) => match (strtolower(trim((string) $status))) {
                'active', 'available', 'published' => 'open',
                'accepted' => 'completed',
                default => strtolower(trim((string) $status)),
            })
            ->filter()
            ->values()
            ->all();

        $query = TradeRoomOffer::query()->orderByDesc('created_at');
        if ($mine) {
            $query->where(fn ($query) => $query->where('user_id', $user->id)->orWhere('counterparty_id', $user->id));
        } else {
            $query->where('status', 'open');
        }
        if ($statuses) {
            $query->whereIn('status', $statuses);
        }

        $offers = $query->limit(100)->get()
            ->map(fn (TradeRoomOffer $offer) => [
                'id' => $offer->id,
                'asset' => $this->roomAsset($offer),
                'side' => $offer->side,
                'quantity' => (float) $offer->grams,
                'unit_price' => (int) $offer->price_per_gram,
                'unit' => $offer->metal === 'coin' ? 'piece' : 'gram',
                'total' => $offer->total(),
                'status' => $offer->status,
                'source' => $offer->source,
                'is_from_bot' => $offer->source === 'telegram_bot',
                'is_mine' => $offer->user_id === $user->id,
                'is_counterparty' => $offer->counterparty_id === $user->id,
                'created_at' => $offer->created_at?->toIso8601String(),
                'completed_at' => $offer->completed_at?->toIso8601String(),
            ]);

        return response()->json(['offers' => $offers]);
    }

    /** ثبت پیشنهاد خرید یا فروش ربات در اتاق معاملاتی با رزرو دارایی. */
    public function tradeRoomOffer(Request $request): JsonResponse
    {
        $this->authorize($request);
        $user = $this->vipUserForChat($request);
        $data = $request->validate([
            'asset' => ['required', 'in:gold,silver_999,silver_995,full_coin,half_coin,quarter_coin'],
            'side' => ['required', 'in:buy,sell'],
            'unit' => ['required', 'in:gram,mesghal,piece'],
            'quantity' => ['required', 'numeric', 'min:0.0001', 'max:1000000'],
            'unit_price' => ['required', 'integer', 'min:1'],
        ]);

        $assets = [
            'gold' => ['metal' => 'gold', 'purity' => '', 'item' => null],
            'silver_999' => ['metal' => 'silver', 'purity' => '999', 'item' => null],
            'silver_995' => ['metal' => 'silver', 'purity' => '995', 'item' => null],
            'full_coin' => ['metal' => 'coin', 'purity' => 'full', 'item' => 'bahar'],
            'half_coin' => ['metal' => 'coin', 'purity' => 'half', 'item' => 'nim'],
            'quarter_coin' => ['metal' => 'coin', 'purity' => 'quarter', 'item' => 'rob'],
        ];
        $asset = $assets[$data['asset']];
        $isCoin = $asset['metal'] === 'coin';
        abort_if($isCoin && $data['unit'] !== 'piece', 422, 'واحد سکه باید piece باشد.');
        abort_if(! $isCoin && $data['unit'] === 'piece', 422, 'واحد طلا و نقره باید gram یا mesghal باشد.');

        $factor = (float) env('MITHQAL_GRAMS', 4.3318);
        $quantity = (float) $data['quantity'];
        $amount = $data['unit'] === 'mesghal' ? round($quantity * $factor, 4) : $quantity;
        $price = $data['unit'] === 'mesghal' ? (int) round($data['unit_price'] / $factor) : (int) $data['unit_price'];
        abort_if($isCoin && floor($amount) !== $amount, 422, 'تعداد سکه باید صحیح باشد.');
        abort_if($asset['metal'] === 'silver' && $amount < 100, 422, 'حداقل سفارش اتاق معاملاتی ۱۰۰ گرم است.');
        $total = (int) round($amount * $price);

        $offer = DB::transaction(function () use ($user, $asset, $isCoin, $data, $amount, $price, $total) {
            $lockedUser = User::query()->lockForUpdate()->findOrFail($user->id);
            if ($data['side'] === 'buy') {
                $wallet = $lockedUser->walletBalance();
                $missing = max(0, $total - $wallet);
                abort_if($missing > 0 && $this->availableCollateralAmount($lockedUser) < $missing, 422, 'موجودی کیف پول یا اعتبار بیعانه دارایی کافی نیست.');
            } elseif ($isCoin) {
                $held = (float) Transaction::query()->where('user_id', $lockedUser->id)->where('item', $asset['item'])->where('status', 'active')->where('type', 'buy')->sum('quantity')
                    - (float) Transaction::query()->where('user_id', $lockedUser->id)->where('item', $asset['item'])->where('status', 'active')->where('type', 'sell')->sum('quantity');
                abort_if($held < $amount, 422, 'موجودی سکه کافی نیست.');
            } else {
                $balance = $asset['metal'] === 'gold' ? $lockedUser->goldBalance() : $lockedUser->silverBalance($asset['purity']);
                abort_if($balance < $amount, 422, 'موجودی انبار کافی نیست.');
            }

            $walletReserve = $data['side'] === 'buy' ? min($lockedUser->walletBalance(), $total) : 0;
            $collateralReserve = $data['side'] === 'buy' ? $total - $walletReserve : 0;
            $offer = TradeRoomOffer::create([
                'user_id' => $lockedUser->id, 'source' => 'telegram_bot',
                'metal' => $asset['metal'], 'item' => $asset['item'],
                'side' => $data['side'], 'purity' => $asset['purity'], 'grams' => $amount,
                'price_per_gram' => $price, 'wallet_reserved_amount' => $walletReserve,
                'collateral_reserved_amount' => $collateralReserve, 'status' => 'open',
            ]);
            if ($data['side'] === 'buy') {
                if ($walletReserve > 0) {
                    WalletTransaction::create(['user_id' => $lockedUser->id, 'amount' => -$walletReserve, 'type' => 'withdraw', 'description' => "رزرو پیشنهاد خرید ربات #{$offer->id}"]);
                }
                $this->reserveCollateral($lockedUser, $collateralReserve);
            } elseif (! $isCoin) {
                $ledger = $asset['metal'] === 'gold' ? GoldLedger::class : SilverLedger::class;
                $values = ['user_id' => $lockedUser->id, 'grams' => -$amount, 'type' => 'offer_escrow', 'reference_type' => TradeRoomOffer::class, 'reference_id' => $offer->id, 'description' => "رزرو پیشنهاد فروش ربات #{$offer->id}"];
                if ($ledger === SilverLedger::class) $values['purity'] = $asset['purity'];
                $ledger::create($values);
            }
            return $offer;
        });

        ActivityLog::record('telegram_room_offer', 'trade', "ثبت پیشنهاد {$data['side']} در اتاق معاملاتی #{$offer->id}", $user->id);
        return response()->json(['id' => $offer->id, 'status' => $offer->status, 'total' => $offer->total()], 201);
    }

